"""Generate 48 random composition programs for C2 (random.Random(7)).

Writes oracle/c2_snippets/sweep_NN.cpp and oracle/c2_sweep.json (the structured description of
each program, which tests/test_c2_compile_checks.py feeds to predict_compiles). Then run
oracle/c2_try_compile.sh to compile every snippet against the real CuTe headers.
"""
import json
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
LHS = [((4, 6), (1, 5)), ((4, 6), (1, 4)), ((4, 8), (8, 1)), ((2, 3, 4), (1, 2, 6)), ((8, 4), (1, 10))]


def cpp_layout(shape, stride):
    if isinstance(shape, int):
        return f"Layout<Int<{shape}>, Int<{stride}>>{{}}"
    s = ",".join(f"Int<{x}>" for x in shape)
    d = ",".join(f"Int<{x}>" for x in stride)
    return f"Layout<Shape<{s}>, Stride<{d}>>{{}}"


def main():
    rng = random.Random(7)
    out = {}
    for i in range(48):
        lhs = LHS[i % len(LHS)]
        if rng.random() < 0.7:
            rhs = (rng.randint(2, 8), rng.choice([0, 1, 2, 3, 4, 5, 6, 8, 10, 12]))
        else:
            rhs = ((rng.randint(2, 4), rng.randint(2, 4)), (rng.choice([1, 2, 3, 4, 6]), rng.choice([4, 6, 8, 12])))
        name = f"sweep_{i:02d}"
        src = (f"// generated by oracle/c2_sweep.py: composition({lhs}, {rhs})\n"
               "#include <cute/tensor.hpp>\nusing namespace cute;\nint main() {\n"
               f"  auto r = composition({cpp_layout(*lhs)}, {cpp_layout(*rhs)});\n"
               "  print(r);\n  return 0;\n}\n")
        (HERE / "c2_snippets" / f"{name}.cpp").write_text(src)
        out[name] = ["composition", [list(lhs[0]), list(lhs[1])], [rhs[0] if isinstance(rhs[0], int) else list(rhs[0]),
                                                                    rhs[1] if isinstance(rhs[1], int) else list(rhs[1])]]
    (HERE / "c2_sweep.json").write_text(json.dumps(out, indent=1))
    print(f"wrote {len(out)} snippets")


if __name__ == "__main__":
    main()
